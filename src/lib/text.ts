/**
 * 한글 줄바꿈 다듬기. keep-all만으로는 막히지 않는 자리에서 줄이 갈리지 않게 한다.
 *  - 붙여 쓴 가운뎃점(「홈·문서」)의 앞뒤: 새 줄이 「·」로 시작하지 않게 단어 결합자(U+2060)를 넣는다.
 *  - 띄어 쓴 가운뎃점(「기획 · Unity」)의 앞 공백: 줄바꿈 없는 공백으로 바꿔 점이 앞말에 붙어 남게 한다.
 *  - 닫는 따옴표·괄호 바로 뒤의 조사(「것”이라고」): 조사만 다음 줄로 떨어지지 않게 묶는다.
 * 단어 결합자는 보이지 않고 보조기기도 읽지 않는다.
 */
const WJ = '\u2060';
const NBSP = '\u00a0';

export function tidy(s: string): string {
  return s
    .replace(/(\S)·(?=\S)/g, `$1${WJ}·${WJ}`)
    .replace(/ · /g, `${NBSP}· `)
    .replace(/([”’」』)])(?=[가-힣])/g, `$1${WJ}`);
}
